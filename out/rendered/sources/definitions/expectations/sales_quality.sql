-- ============================================================
-- Sales data quality expectations
-- ============================================================

-- No NULL customer IDs in the customers table
ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT
    TO TABLE SALES_DB_DEV.RAW.CUSTOMERS
    ON (CUSTOMER_ID)
    EXPECTATION NO_NULL_CUSTOMER_IDS (value = 0);

-- No NULL order IDs
ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT
    TO TABLE SALES_DB_DEV.RAW.ORDERS
    ON (ORDER_ID)
    EXPECTATION NO_NULL_ORDER_IDS (value = 0);

-- Every order must reference a customer
ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT
    TO TABLE SALES_DB_DEV.RAW.ORDERS
    ON (CUSTOMER_ID)
    EXPECTATION NO_ORPHAN_ORDERS (value = 0);

-- No NULL item IDs in order items
ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.NULL_COUNT
    TO TABLE SALES_DB_DEV.RAW.ORDER_ITEMS
    ON (ITEM_ID)
    EXPECTATION NO_NULL_ITEM_IDS (value = 0);

-- Quantities must be positive
ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.MIN
    TO TABLE SALES_DB_DEV.RAW.ORDER_ITEMS
    ON (QUANTITY)
    EXPECTATION POSITIVE_QUANTITIES (value > 0);

-- Revenue in the pipeline should never be negative
ATTACH DATA METRIC FUNCTION SNOWFLAKE.CORE.MIN
    TO DYNAMIC TABLE SALES_DB_DEV.ANALYTICS.ORDER_SUMMARY
    ON (LINE_REVENUE)
    EXPECTATION NON_NEGATIVE_REVENUE (value >= 0);