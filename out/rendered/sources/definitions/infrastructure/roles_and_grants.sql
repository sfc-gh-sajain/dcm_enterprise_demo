-- ============================================================
-- Roles & Grants — domain-specific read roles + cross-grants
-- ============================================================

-- --- Databases & Schemas (must exist before grants) ---

DEFINE DATABASE SALES_DB_DEV;
DEFINE SCHEMA   SALES_DB_DEV.RAW;
DEFINE SCHEMA   SALES_DB_DEV.ANALYTICS;
DEFINE SCHEMA   SALES_DB_DEV.SERVE;

DEFINE DATABASE MARKETING_DB_DEV;
DEFINE SCHEMA   MARKETING_DB_DEV.RAW;
DEFINE SCHEMA   MARKETING_DB_DEV.ANALYTICS;

-- --- Roles ---

DEFINE ROLE SALES_ANALYST_DEV;
DEFINE ROLE MARKETING_ANALYST_DEV;

-- --- Sales grants ---

GRANT USAGE ON DATABASE  SALES_DB_DEV           TO ROLE SALES_ANALYST_DEV;
GRANT USAGE ON SCHEMA    SALES_DB_DEV.RAW       TO ROLE SALES_ANALYST_DEV;
GRANT USAGE ON SCHEMA    SALES_DB_DEV.ANALYTICS TO ROLE SALES_ANALYST_DEV;
GRANT USAGE ON SCHEMA    SALES_DB_DEV.SERVE     TO ROLE SALES_ANALYST_DEV;
GRANT SELECT ON ALL TABLES         IN DATABASE SALES_DB_DEV TO ROLE SALES_ANALYST_DEV;
GRANT SELECT ON ALL DYNAMIC TABLES IN DATABASE SALES_DB_DEV TO ROLE SALES_ANALYST_DEV;
GRANT SELECT ON ALL VIEWS          IN DATABASE SALES_DB_DEV TO ROLE SALES_ANALYST_DEV;
GRANT USAGE ON WAREHOUSE SALES_WH_DEV TO ROLE SALES_ANALYST_DEV;

-- --- Marketing grants ---

GRANT USAGE ON DATABASE  MARKETING_DB_DEV           TO ROLE MARKETING_ANALYST_DEV;
GRANT USAGE ON SCHEMA    MARKETING_DB_DEV.RAW       TO ROLE MARKETING_ANALYST_DEV;
GRANT USAGE ON SCHEMA    MARKETING_DB_DEV.ANALYTICS TO ROLE MARKETING_ANALYST_DEV;
GRANT SELECT ON ALL TABLES         IN DATABASE MARKETING_DB_DEV TO ROLE MARKETING_ANALYST_DEV;
GRANT SELECT ON ALL DYNAMIC TABLES IN DATABASE MARKETING_DB_DEV TO ROLE MARKETING_ANALYST_DEV;
GRANT USAGE ON WAREHOUSE MARKETING_WH_DEV TO ROLE MARKETING_ANALYST_DEV;

-- --- Grant roles to demo user ---

GRANT ROLE SALES_ANALYST_DEV     TO USER SJAIN;
GRANT ROLE MARKETING_ANALYST_DEV TO USER SJAIN;