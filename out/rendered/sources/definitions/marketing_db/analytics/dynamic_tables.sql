-- Marketing analytics — campaign performance dynamic table
-- ============================================================

DEFINE DYNAMIC TABLE MARKETING_DB_DEV.ANALYTICS.CAMPAIGN_PERFORMANCE
    WAREHOUSE = MARKETING_WH_DEV
    TARGET_LAG = '1 hour'
    INITIALIZE = 'ON_SCHEDULE'
    DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES'
AS
SELECT
    c.CAMPAIGN_ID,
    c.CAMPAIGN_NAME,
    c.CHANNEL,
    c.BUDGET,
    c.STATUS        AS CAMPAIGN_STATUS,
    COUNT(l.LEAD_ID)                               AS TOTAL_LEADS,
    COUNT(CASE WHEN l.LEAD_STATUS = 'CONVERTED' THEN 1 END) AS CONVERTED_LEADS,
    ROUND(COUNT(CASE WHEN l.LEAD_STATUS = 'CONVERTED' THEN 1 END)
          / NULLIF(COUNT(l.LEAD_ID), 0) * 100, 2)  AS CONVERSION_RATE_PCT,
    ROUND(c.BUDGET / NULLIF(COUNT(l.LEAD_ID), 0), 2) AS COST_PER_LEAD
FROM MARKETING_DB_DEV.RAW.CAMPAIGNS c
LEFT JOIN MARKETING_DB_DEV.RAW.LEADS l ON c.CAMPAIGN_ID = l.CAMPAIGN_ID
GROUP BY c.CAMPAIGN_ID, c.CAMPAIGN_NAME, c.CHANNEL, c.BUDGET, c.STATUS;