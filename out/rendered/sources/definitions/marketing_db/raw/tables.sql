-- ============================================================
-- Marketing RAW tables — campaign and lead data
-- ============================================================

DEFINE TABLE MARKETING_DB_DEV.RAW.CAMPAIGNS (
    CAMPAIGN_ID   NUMBER       NOT NULL,
    CAMPAIGN_NAME VARCHAR(200) NOT NULL,
    CHANNEL       VARCHAR(50),
    BUDGET        NUMBER(12,2),
    START_DATE    DATE,
    END_DATE      DATE,
    STATUS        VARCHAR(20)  DEFAULT 'ACTIVE'
)
CHANGE_TRACKING = TRUE
DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES';

DEFINE TABLE MARKETING_DB_DEV.RAW.LEADS (
    LEAD_ID       NUMBER       NOT NULL,
    CAMPAIGN_ID   NUMBER       NOT NULL,
    LEAD_NAME     VARCHAR(200),
    EMAIL         VARCHAR(200),
    LEAD_SOURCE   VARCHAR(50),
    LEAD_STATUS   VARCHAR(30)  DEFAULT 'NEW',
    CREATED_AT    TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
)
CHANGE_TRACKING = TRUE
DATA_METRIC_SCHEDULE = 'TRIGGER_ON_CHANGES';